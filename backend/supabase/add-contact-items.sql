-- Flexible contact list (replaces the fixed email1/email2/github/linkedin columns).
-- Safe to run more than once.
create table if not exists contact_items (
    id bigint generated by default as identity primary key,
    type text not null default 'link' check (type in ('email', 'link')),
    label text not null default '',
    value text not null,
    display_order int not null default 0
);
alter table contact_items enable row level security;

-- Copy the existing contact info over (only if the new table is still empty).
insert into contact_items (type, label, value, display_order)
select type, label, value, display_order
from (
    select 'email' as type, 'Email' as label, email1 as value, 0 as display_order from contact where id = 1
    union all select 'email', 'Email', email2, 1 from contact where id = 1
    union all select 'link', 'GITHUB', github, 2 from contact where id = 1
    union all select 'link', 'LINKEDIN', linkedin, 3 from contact where id = 1
) old
where coalesce(value, '') <> ''
  and not exists (select 1 from contact_items);
