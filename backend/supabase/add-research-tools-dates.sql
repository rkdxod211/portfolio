-- About > Tools: comma-separated lists per category, e.g. {"languages": "Python, Java"}.
alter table about add column if not exists tools jsonb not null default '{}'::jsonb;
update about set tools = '{
    "languages": "Python, Java, JavaScript, HTML/CSS",
    "frameworks": "React, Node.js, Express",
    "databases": "PostgreSQL, Supabase, MySQL, Vercel",
    "devtools": "Git, GitHub, VS Code"
}'::jsonb
where id = 1 and tools = '{}'::jsonb;

-- Experience: free-text dates ("Sep 2025"). A start with no end shows as "Present".
alter table experience_clubs add column if not exists start_date text not null default '';
alter table experience_clubs add column if not exists end_date text not null default '';
alter table experience_work add column if not exists start_date text not null default '';
alter table experience_work add column if not exists end_date text not null default '';

-- Move the dates that were typed into the CNAPS.ai detail into the new fields.
update experience_work set detail = 'CNAPS.ai', start_date = 'Oct 2026'
where detail = 'CNAPS.ai (Oct 2026 - Present)';

-- Research entries. `tags` is comma-separated; an empty end_date shows as "Present".
create table if not exists research (
    id bigint generated by default as identity primary key,
    title text not null default '',
    role text not null default '',        -- e.g. Undergraduate Researcher
    lab text not null default '',         -- lab or group name, optional
    advisor text not null default '',     -- PI / mentor, optional
    location text not null default '',    -- e.g. Madison, WI
    start_date text not null default '',
    end_date text not null default '',
    tags text not null default '',        -- related fields
    question text not null default '',    -- research question
    description text not null default '',
    outcomes text not null default '',    -- papers, posters, talks, optional
    link text not null default '',        -- lab or project page, optional
    display_order int not null default 0
);
alter table research enable row level security;

