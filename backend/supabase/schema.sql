    id bigint generated by default as identity primary key,
    username text unique not null,
    password text not null -- bcrypt hash
);

-- Projects themselves come from GitHub; only the counters are stored here,
-- keyed by the GitHub repository id (stable across renames).
create table if not exists project_stats (
    repo_id bigint primary key,
    likes int not null default 0,
    views int not null default 0,
    downloads int not null default 0,
    hidden boolean not null default false -- admin's show/hide choice
);
alter table project_stats add column if not exists hidden boolean not null default false;

-- Atomic counters
create or replace function increment_visitor(p_date date)
returns int language sql as $$
    insert into visitor_stats (date, count) values (p_date, 1)
    on conflict (date) do update set count = visitor_stats.count + 1
    returning count;
$$;

create or replace function increment_project_stat(p_repo_id bigint, p_field text)
returns int language plpgsql as $$
declare result int;
begin
    if p_field not in ('likes', 'views', 'downloads') then
        raise exception 'invalid field %', p_field;
    end if;
    execute format(
        'insert into project_stats (repo_id, %1$I) values ($1, 1)
         on conflict (repo_id) do update set %1$I = project_stats.%1$I + 1
         returning %1$I', p_field)
    into result using p_repo_id;
    return result;
end;
$$;

